// Import necessary modules and set up test environment
const assert = require('assert').strict;
const request = require('supertest');
const app = require('../app');
const server = app.listen(3000);

// Test Item model and CRUD operations
describe('Item model tests', () => {
  test('should create an item', () => {
    const item = {
     name: 'Test Item',
     price: 10,
     description: 'Test Item'
  };
  const response = request(server)
    .post('/api/items')
    .send(item)
    .expect(201);
  assert.equal(response.status, 201);
  assert.equal(response.body.message, 'Item created');
  assert.equal(response.body.data.name, item.name);
  assert.equal(response.body.data.price, item.price);
  assert.equal(response.body.data.description, item.description);
});

test('should retrieve items', () => {
  const response = request(server)
    .get('/api/items')
    .expect(200);
  assert.equal(response.status, 200);
  const items = response.body;
  assert.equal(items.length, 1);
  assert.equal(items[0].name, 'Test Item');
  assert.equal(items[0].price, 10);
  assert.equal(items[0].description, 'Test Item');
});

test('should update item', () => {
  const item = {
    name: 'Test Item',
    price: 10,
    description: 'Test Item'
  };
  const response = request(server)
    .put('/api/items/1')
    .send(item)
    .expect(200);
  assert.equal(response.status, 200);
  const item = response.body;
  assert.equal(item.name, 'Test Item');
  assert.equal(item.price, 10);
  assert.equal(item.description, 'Test Item');
});

test('should delete item', () => {
  const itemId = 1;
  const response = request(server)
    .delete('/api/items/' + itemId)
    .expect(204);
  assert.equal(response.status, 204);
});

test('should return 404 for non-existent item', () => {
  const itemId = 999;
  const response = request(server)
    .get('/api/items/' + itemId)
    .expect(404);
  assert.equal(response.status, 404);
});
});
